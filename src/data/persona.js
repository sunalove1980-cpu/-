export function pickReaction(mode) {
  const list = REACTIONS[mode] ?? REACTIONS.F;
  return list[Math.floor(Math.random() * list.length)];
}

export function pickFallbackReply(mode, userText) {
  const bank = FALLBACK_REPLIES[mode] ?? FALLBACK_REPLIES.F;
  const hit = Object.entries(bank.keywords).find(([keyword]) => userText.includes(keyword));
  const pool = hit ? hit[1] : bank.default;
  return pool[Math.floor(Math.random() * pool.length)];
}
